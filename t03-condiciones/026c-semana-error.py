# Nombre de un día de la semana

# Tercera versión: "else" sin "elif", incorrecto

dia = int(input("Dime el número de día (1 a 7) "))

if dia == 1:
    print("Lunes")
if dia == 2:
    print("Martes")
if dia == 3:
    print("Miércoles")
if dia == 4:
    print("Jueves")
if dia == 5:
    print("Viernes")
if dia == 6:
    print("Sábado")
if dia == 7:
    print("Domingo")
else:
    print("Día incorrecto")


