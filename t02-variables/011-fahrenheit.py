# Vamos a crear un conversor de
# grados Fahrenheit a grados Celsius (centígrados).

# Debes encontrar la "fórmula" que te
# permite convertir de uno a otro y crear
# un programa que la aplique.

fahrenheit = int(input("Dime los grados Fahrenheit: "))
celsius = (fahrenheit-32) * 5 / 9
print("En Celsius son", celsius)
